// Headless walkthrough of the primary flow + keyboard checks. Usage: node scripts/verify.mjs [baseUrl]
import { chromium } from '@playwright/test'
const BASE = process.argv[2] ?? 'http://localhost:4173'
const OUT = new URL('../../verify/', import.meta.url).pathname
const results = []
const check = (name, ok, extra = '') => { results.push({ name, ok, extra }); console.log(`${ok ? 'PASS' : 'FAIL'} ${name} ${extra}`) }

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 987 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
const shot = (n) => page.screenshot({ path: `${OUT}${n}.png`, fullPage: true })
const next = () => page.getByRole('button', { name: 'Next' }).click({ force: true })
const vis = (loc) => loc.first().waitFor({ timeout: 4000 }).then(() => true, () => false)
const settle = () => page.waitForTimeout(900)

await page.goto(BASE + '/')
await page.evaluate(() => localStorage.clear())
await page.goto(BASE + '/')
await page.waitForURL('**/apply/coverage')
check('root redirects to coverage', page.url().endsWith('/apply/coverage'))
await shot('01-coverage-empty')
await next()
check('Next blocked without coverage', page.url().endsWith('/apply/coverage') && await page.getByText('Select at least one coverage').isVisible())
// keyboard: tab to first checkbox, space toggles
await page.getByRole('checkbox', { name: 'General Liability', exact: true }).focus()
await page.keyboard.press('Space')
await page.getByRole('checkbox', { name: "Workers' Compensation", exact: true }).focus()
await page.keyboard.press('Space')
check('keyboard toggles coverage checkboxes', await page.getByRole('checkbox', { name: 'General Liability', exact: true }).isChecked() && await page.getByRole('checkbox', { name: "Workers' Compensation", exact: true }).isChecked())
check('rail shows simulated loading after answer', await page.getByText('Checking eligibility').isVisible())
await settle()
check('BiBERK eligible after GL+WC', await page.locator('aside').getByText('BiBERK').count() > 0)
await shot('02-coverage-selected')
await next(); await settle()
check('business details route', page.url().endsWith('/apply/business-details'))
await shot('03-business-details')
await page.getByRole('button', { name: 'Increase Number of Full Time Employees' }).press('Enter')
check('stepper increments via keyboard', (await page.getByLabel('Number of Full Time Employees', { exact: true }).inputValue()) === '3')
await next(); await settle()
check('operations route', page.url().endsWith('/apply/operations'))
await shot('04-operations')
await next(); await settle()
await shot('05-additional-info')
await next(); await settle()
check('first carrier step is BiBERK', page.url().endsWith('/apply/carrier/biberk'))
// templated: answer all via keyboard (radio groups)
for (const g of await page.getByRole('radio', { name: 'NO' }).all()) await g.check()
await next(); await page.waitForTimeout(1000)
check('advance to Chubb', page.url().endsWith('/apply/carrier/chubb'))
await shot('06-chubb-empty')
await next()
check('Chubb validation message', await page.getByRole('alert').isVisible())
const radios = await page.getByRole('radio', { name: 'NO' }).all()
for (const r of radios) await r.check()
await page.getByLabel(/Workers' Compensation claims/).fill('0')
await page.getByLabel(/previous Workers' Compensation insurer/).selectOption('Self-Insured')
await settle()
await shot('07-chubb-answered')
await next(); await page.waitForTimeout(1200)
const dlg = page.getByRole('dialog')
check('Chubb WC timeout modal opens', await dlg.isVisible())
await shot('08-chubb-timeout-modal')
await page.keyboard.press('Escape')
check('Esc closes modal', !(await dlg.isVisible()))
await next(); await page.waitForTimeout(1200)
await page.getByRole('button', { name: 'CLOSE', exact: true }).click()
await page.waitForURL('**/apply/carrier/cna'); await page.getByRole('heading', { name: 'CNA' }).waitFor()
check('advance to CNA', page.url().endsWith('/apply/carrier/cna'))
for (const r of await page.getByRole('radio', { name: 'NO' }).all()) await r.check()
await settle(); await shot('09-cna-answered')
await next(); await page.waitForTimeout(1200)
await page.getByRole('button', { name: 'CLOSE', exact: true }).click()
for (const id of ['hiscox', 'liberty-mutual', 'travelers']) {
  await page.waitForURL(`**/apply/carrier/${id}`); await page.waitForTimeout(200)
  for (const r of await page.getByRole('radio', { name: 'NO' }).all()) await r.check()
  await next(); await page.waitForTimeout(1200)
}
check('lands on quote page CHUBB GL', page.url().endsWith('/quotes/chubb-gl'))
check('CHUBB GL premium $1,720', await page.getByText('$1,720').isVisible())
await shot('10-quote-chubb-gl')
await page.getByRole('link', { name: /CHUBB.*WC/ }).click()
check('Pathpoint uses Figma purple status icon', (await page.getByRole('link', { name: /Pathpoint/ }).locator('img[src*="status-wholesale"], img[src^="data:"]').count()) > 0)
check('CHUBB WC shows timeout', await vis(page.getByText(/returned a timeout error/)))
await shot('11-quote-chubb-wc')
await page.getByRole('link', { name: /Pathpoint/ }).click()
check('Pathpoint modal opens', await vis(page.getByRole('dialog')))
await shot('12-quote-pathpoint-modal')
await page.getByRole('button', { name: 'CLOSE', exact: true }).click()
// disabled with reason: focus Continue to bind -> tooltip visible
const bind = page.getByRole('button', { name: /Continue to bind/i })
await bind.focus()
check('Bind disabled with visible reason on focus', (await bind.getAttribute('aria-disabled')) === 'true' && await page.getByRole('tooltip', { name: /binding a policy/ }).isVisible())
await shot('13-bind-disabled-reason')
// keyboard tab order reaches quote list links with visible focus
await page.getByRole('link', { name: 'Go back to application form' }).click()
check('back to application (live state)', page.url().includes('/apply/carrier/travelers'))
await settle(); await shot('14-application-live')
check('Estimated Annual Premium panel in live state', await vis(page.getByRole('heading', { name: 'Estimated Annual Premium' })) && await page.getByText('$739 - $1,204').isVisible())
await page.getByRole('button', { name: 'Collapse estimate' }).press('Enter')
check('premium panel collapses via keyboard', !(await page.getByText('$739 - $1,204').isVisible()))
// nested route refresh
await page.goto(BASE + '/quotes/hiscox-gl')
check('nested route refresh works (/quotes/hiscox-gl)', await page.getByText('$3,178').isVisible())
await page.goto(BASE + '/apply/carrier/chubb')
check('nested route refresh works (/apply/carrier/chubb)', await page.getByRole('heading', { name: 'Chubb' }).isVisible())
// reset
await page.getByRole('button', { name: 'Reset demo' }).click()
check('reset returns to empty coverage', page.url().endsWith('/apply/coverage') && !(await page.getByRole('checkbox', { name: 'General Liability', exact: true }).isChecked()))
// keyboard Tab sequence sanity: first focusable items
await page.goto(BASE + '/apply/coverage')
const seq = []
for (let i = 0; i < 6; i++) { await page.keyboard.press('Tab'); seq.push(await page.evaluate(() => (document.activeElement?.getAttribute('aria-label') || document.activeElement?.textContent || document.activeElement?.tagName || '').trim().slice(0, 40))) }
console.log('Tab order:', seq.join(' | '))
const outline = await page.evaluate(() => getComputedStyle(document.activeElement).outlineStyle)
check('focus ring visible (outline)', outline !== 'none', outline)
check('no console/page errors', errors.length === 0, errors.join('; '))
await browser.close()
const failed = results.filter((r) => !r.ok).length
console.log(`\n${results.length - failed}/${results.length} checks passed`)
process.exit(failed ? 1 : 0)
